import {
  Activity,
  AlertCircle,
  BarChart3,
  BookOpen,
  ClipboardList,
  History,
  Home,
  LogOut,
  MapPin,
  Menu,
  Shield,
  Stethoscope,
  User as UserIcon,
  X
} from 'lucide-react';
import React, { useState } from 'react';
import { User } from '../types/index.js';

interface NavbarProps {
  currentUser: User | null;
  activePage?: string;
  currentPage?: string;
  onNavigate: (page: string, params?: any) => void;
  onLogout: () => void;
}

export const Navbar: React.FC<NavbarProps> = ({
  currentUser,
  activePage,
  currentPage,
  onNavigate,
  onLogout,
}) => {
  const current = activePage || currentPage || 'home';
  const [mobileOpen, setMobileOpen] = useState(false);

  const navItems = [
    { id: 'home', label: 'Home', icon: Home },
    { id: 'checker', label: 'Symptom Checker', icon: Stethoscope },
    { id: 'diseases', label: 'Disease Library', icon: BookOpen },
    { id: 'ml-evaluation', label: 'ML Analytics & Docs', icon: BarChart3 },
    { id: 'find-care', label: 'Locate Care', icon: MapPin },
  ];

  if (currentUser) {
    navItems.splice(2, 0, { id: 'dashboard', label: 'Dashboard', icon: ClipboardList });
    navItems.splice(3, 0, { id: 'history', label: 'My History', icon: History });
  }

  if (currentUser?.role === 'admin') {
    navItems.push({ id: 'admin', label: 'Admin Portal', icon: Shield });
  }

  return (
    <header className="sticky top-0 z-40 bg-white/95 backdrop-blur-md border-b border-slate-200">
      {/* Top Disclaimer Ticker */}
      <div className="bg-amber-50 border-b border-amber-200/80 px-4 py-1.5 text-xs text-amber-900 flex items-center justify-center gap-2">
        <AlertCircle className="w-3.5 h-3.5 text-amber-600 shrink-0" />
        <span>
          <strong>Educational AI Prototype:</strong> Predictions are generated by machine learning algorithms and are strictly not a medical diagnosis. In an emergency, dial 100 or 102 immediately.
        </span>
      </div>

      <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8">
        <div className="flex items-center justify-between h-16">
          {/* Brand */}
          <button
            id="nav-brand-btn"
            onClick={() => onNavigate('home')}
            className="flex items-center gap-3 text-left focus:outline-none group"
          >
            <div className="w-10 h-10 rounded-xl bg-blue-600 text-white flex items-center justify-center shadow-md shadow-blue-600/20 group-hover:bg-blue-700 transition-colors">
              <Activity className="w-5 h-5" />
            </div>
            <div>
              <div className="font-bold text-base text-slate-900 leading-tight tracking-tight flex items-center gap-1.5">
                AI Disease Prediction System
                <span className="text-[10px] uppercase font-semibold tracking-wider bg-blue-100 text-blue-800 px-1.5 py-0.5 rounded">
                  ML-v2.1
                </span>
              </div>
              <p className="text-xs text-slate-500 font-normal">Intelligent Symptom Classification Engine</p>
            </div>
          </button>

          {/* Desktop Navigation Links */}
          <nav className="hidden lg:flex items-center gap-1">
            {navItems.map((item) => {
              const Icon = item.icon;
              const isActive = current === item.id;
              return (
                <button
                  key={item.id}
                  id={`nav-link-${item.id}`}
                  onClick={() => onNavigate(item.id)}
                  className={`px-3 py-2 rounded-lg text-sm font-medium flex items-center gap-1.5 transition-colors ${
                    isActive
                      ? 'bg-blue-50 text-blue-700 font-semibold'
                      : 'text-slate-600 hover:text-slate-900 hover:bg-slate-100'
                  }`}
                >
                  <Icon className={`w-4 h-4 ${isActive ? 'text-blue-600' : 'text-slate-400'}`} />
                  {item.label}
                </button>
              );
            })}
          </nav>

          {/* Right Action / Auth Buttons */}
          <div className="hidden lg:flex items-center gap-3">
            {currentUser ? (
              <div className="flex items-center gap-2">
                <button
                  id="nav-profile-btn"
                  onClick={() => onNavigate('profile')}
                  className={`flex items-center gap-2 pl-2 pr-3 py-1.5 rounded-full border transition-colors ${
                    current === 'profile'
                      ? 'border-blue-400 bg-blue-50 text-blue-900'
                      : 'border-slate-200 bg-white hover:bg-slate-50 text-slate-700'
                  }`}
                >
                  <div className="w-7 h-7 rounded-full bg-blue-100 text-blue-800 flex items-center justify-center font-semibold text-xs">
                    {currentUser.name.charAt(0).toUpperCase()}
                  </div>
                  <div className="text-left text-xs">
                    <span className="font-semibold block leading-tight max-w-[110px] truncate">
                      {currentUser.name}
                    </span>
                    <span className="text-[10px] text-slate-400 uppercase tracking-wider font-medium">
                      {currentUser.role}
                    </span>
                  </div>
                </button>

                <button
                  id="nav-logout-btn"
                  onClick={onLogout}
                  title="Log out"
                  className="p-2 text-slate-400 hover:text-rose-600 hover:bg-rose-50 rounded-lg transition-colors"
                >
                  <LogOut className="w-4 h-4" />
                </button>
              </div>
            ) : (
              <div className="flex items-center gap-2">
                <button
                  id="nav-login-btn"
                  onClick={() => onNavigate('login')}
                  className="px-3.5 py-2 text-sm font-medium text-slate-700 hover:text-blue-700 hover:bg-slate-100 rounded-lg transition-colors"
                >
                  Login
                </button>
                <button
                  id="nav-register-btn"
                  onClick={() => onNavigate('register')}
                  className="px-4 py-2 text-sm font-semibold text-white bg-blue-600 hover:bg-blue-700 rounded-lg shadow-sm shadow-blue-600/30 transition-colors"
                >
                  Register
                </button>
              </div>
            )}
          </div>

          {/* Mobile Menu Button */}
          <div className="flex lg:hidden items-center gap-2">
            <button
              id="mobile-menu-toggle-btn"
              onClick={() => setMobileOpen(!mobileOpen)}
              className="p-2 rounded-lg text-slate-600 hover:bg-slate-100"
            >
              {mobileOpen ? <X className="w-6 h-6" /> : <Menu className="w-6 h-6" />}
            </button>
          </div>
        </div>
      </div>

      {/* Mobile dropdown */}
      {mobileOpen && (
        <div className="lg:hidden border-b border-slate-200 bg-white px-4 pt-2 pb-4 space-y-1">
          {navItems.map((item) => {
            const Icon = item.icon;
            const isActive = current === item.id;
            return (
              <button
                key={item.id}
                onClick={() => {
                  onNavigate(item.id);
                  setMobileOpen(false);
                }}
                className={`w-full text-left px-3 py-2.5 rounded-lg text-sm font-medium flex items-center gap-2 ${
                  isActive ? 'bg-blue-50 text-blue-700 font-semibold' : 'text-slate-700 hover:bg-slate-100'
                }`}
              >
                <Icon className={`w-4 h-4 ${isActive ? 'text-blue-600' : 'text-slate-400'}`} />
                {item.label}
              </button>
            );
          })}

          <div className="pt-3 border-t border-slate-100">
            {currentUser ? (
              <div className="space-y-2">
                <button
                  onClick={() => {
                    onNavigate('profile');
                    setMobileOpen(false);
                  }}
                  className="w-full text-left px-3 py-2 text-sm font-medium text-slate-700 flex items-center gap-2"
                >
                  <UserIcon className="w-4 h-4 text-slate-400" />
                  My Profile ({currentUser.name})
                </button>
                <button
                  onClick={() => {
                    onLogout();
                    setMobileOpen(false);
                  }}
                  className="w-full text-left px-3 py-2 text-sm font-medium text-rose-600 flex items-center gap-2"
                >
                  <LogOut className="w-4 h-4" />
                  Log Out
                </button>
              </div>
            ) : (
              <div className="grid grid-cols-2 gap-2 pt-1">
                <button
                  onClick={() => {
                    onNavigate('login');
                    setMobileOpen(false);
                  }}
                  className="w-full py-2 text-center text-sm font-medium border border-slate-300 rounded-lg text-slate-700"
                >
                  Login
                </button>
                <button
                  onClick={() => {
                    onNavigate('register');
                    setMobileOpen(false);
                  }}
                  className="w-full py-2 text-center text-sm font-semibold bg-blue-600 text-white rounded-lg shadow-sm"
                >
                  Register
                </button>
              </div>
            )}
          </div>
        </div>
      )}
    </header>
  );
};
